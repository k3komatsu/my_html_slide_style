import assert from 'node:assert/strict';
import { readFile, writeFile, rm, cp } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { fixture } from './fixture.mjs';
import { openBrowser } from '../tools/browser.mjs';
import { build } from '../tools/build.mjs';
import { model, exportSelection, slideSections, identifySlides, selectedHtml } from '../tools/visibility.mjs';

const repo = fileURLToPath(new URL('../', import.meta.url));
const run = (script, args) => new Promise(resolve => {
  const child = spawn(process.execPath, [path.resolve(repo, script), ...args], { cwd: repo });
  let output = ''; child.stdout.on('data', data => output += data); child.stderr.on('data', data => output += data);
  child.on('error', error => { throw error; }); child.on('exit', code => resolve({ code, output }));
});
const { root } = await fixture();
const browser = await openBrowser({ label: 'visibility' });
const { evaluate, cdp } = browser;
const target = path.join(root, 'index.html');
const settle = () => evaluate(`(async () => { await MathJax.startup.promise; await new Promise(resolve => setTimeout(resolve, 150)); })()`);
let settings;
try {
  const sample = '<section class="slide" id="stable"><section><p>Nested</p></section></section><!-- <section class="slide"> --><script>const tag="<section>";</script>';
  assert.equal(slideSections(identifySlides(sample)).length, 1);
  assert.equal(slideSections('<section title="class=\'slide\'" class="other"></section>').length, 0);
  assert.equal(slideSections(identifySlides('<section class="slide" id="a&#35;b"></section>'))[0].id, 'a#b');
  assert.throws(() => model.normalize({ version: 1, modes: [{ id: 'all', name: 'A' }], hidden: {} }));
  assert.throws(() => model.normalize({ version: 1, modes: [{ id: 'a', name: 'A' }, { id: 'b', name: 'A' }], hidden: {} }));
  assert.throws(() => model.normalize({ version: 1, modes: [], hidden: { stable: ['unknown'] } }));
  await cdp('Browser.setDownloadBehavior', { behavior: 'allow', downloadPath: root });
  await browser.load(target);
  assert.equal(await evaluate('SlideDeck.visibility.visibleSlides.length'), 3);
  await evaluate(`SlideDeck.slides[0].focus(); dispatchEvent(new KeyboardEvent('keydown', {key:'M', bubbles:true})); document.querySelector('.slide.is-current .visibility-edit').click()`);
  assert.equal(await evaluate(`document.querySelector('.visibility-dialog').open`), true);
  await evaluate(`(() => {
    const form = document.querySelector('.visibility-add');
    for (const name of ['授業', '配布', '自習']) { form.elements.mode.value = name; form.requestSubmit(); }
    const check = [...document.querySelectorAll('.visibility-hide')].find(input => input.dataset.slideId === SlideDeck.slides[1].dataset.slideId);
    check.click();
    const select = document.querySelector('.visibility-dialog .visibility-mode'); select.value = SlideDeck.visibility.settings.modes[0].id; select.dispatchEvent(new Event('change'));
  })()`);
  assert.equal(await evaluate('SlideDeck.visibility.visibleSlides.length'), 2);
  assert.equal(await evaluate('SlideDeck.visibility.settings.modes.length'), 3);
  await evaluate(`(() => {
    const input = document.querySelector('.visibility-modes input'); input.value = '授業（対面）'; input.dispatchEvent(new Event('change'));
    const renamed = document.querySelector('.visibility-modes input'); renamed.value = '授業'; renamed.dispatchEvent(new Event('change'));
    window.confirm = () => true; document.querySelectorAll('.visibility-modes button')[2].click();
    const form = document.querySelector('.visibility-add'); form.elements.mode.value = '自習'; form.requestSubmit();
    form.elements.mode.value = '授業'; form.requestSubmit();
  })()`);
  assert.equal(await evaluate('SlideDeck.visibility.settings.modes.length'), 3, 'Rename and delete work; duplicate mode names are rejected');
  assert((await evaluate(`document.querySelector('.visibility-status').textContent`)).includes('重複'));
  const initialIndex = await evaluate('SlideDeck.current');
  await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'ArrowRight', code: 'ArrowRight' });
  assert.equal(await evaluate('SlideDeck.current'), initialIndex, 'Dialog keys never advance the deck');
  await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape' });
  await cdp('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape' });
  assert.equal(await evaluate(`document.querySelector('.visibility-dialog').open`), false);
  await settle();
  await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'ArrowRight', code: 'ArrowRight' });
  assert.equal(await evaluate('SlideDeck.current'), 2, 'Forward skips hidden content');
  await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'ArrowLeft', code: 'ArrowLeft' });
  assert.equal(await evaluate('SlideDeck.current'), 0, 'Back skips hidden content');
  await evaluate(`SlideDeck.show(1)`);
  assert.equal(await evaluate('SlideDeck.current'), 2, 'Direct links cannot show a hidden slide');
  assert.equal(await evaluate(`SlideDeck.slides[2].querySelector('.slide-page').getAttribute('aria-label')`), '全1ページ中1ページ');
  assert.equal(await evaluate(`SlideDeck.slides[2].querySelectorAll('.slide-page mjx-container [data-mml-node="mfrac"]').length`), 1);
  const rings = await evaluate(`[...document.querySelectorAll('.slide-timer')].map(el => el.parentElement.closest('.slide').dataset.slideId)`);
  await evaluate('SlideDeck.toggleOverview()');
  assert.equal(await evaluate(`getComputedStyle(SlideDeck.slides[1]).display`), 'none');
  assert.equal(await evaluate(`document.querySelectorAll('.minimap__tick:not([hidden])').length`), 2);
  await evaluate('SlideDeck.toggleOverview()');
  await cdp('Emulation.setEmulatedMedia', { media: 'print' });
  assert.equal(await evaluate(`getComputedStyle(SlideDeck.slides[1]).display`), 'none');
  assert.equal(await evaluate(`getComputedStyle(SlideDeck.slides[2]).breakAfter`), 'auto');
  await cdp('Emulation.setEmulatedMedia', { media: 'screen' });
  await browser.load(target);
  assert.equal(await evaluate('SlideDeck.visibility.visibleSlides.length'), 2, 'Reload restores the mode and conditions');
  await evaluate('SlideDeck.visibility.setMode("all")'); await settle();
  assert.equal(await evaluate('SlideDeck.visibility.visibleSlides.length'), 3);
  assert.deepEqual(await evaluate(`[...document.querySelectorAll('.slide-timer')].map(el => el.parentElement.closest('.slide').dataset.slideId)`), rings, 'Renumbering preserves timers');
  assert.equal(await evaluate(`SlideDeck.slides[1].dataset.no`), '1');
  assert.equal(await evaluate(`SlideDeck.slides[2].dataset.no`), '2');
  await evaluate(`(() => { for (let i = 0; i < 20; i++) SlideDeck.visibility.setMode(i % 2 ? 'all' : '授業'); })()`);
  await settle();
  assert.equal(await evaluate(`SlideDeck.slides[2].querySelector('.slide-page').getAttribute('aria-label')`), '全2ページ中2ページ');
  assert.equal(await evaluate(`document.querySelectorAll('mjx-merror, [data-mjx-error]').length`), 0, 'Rapid mode changes do not corrupt MathJax');
  for (const [width, height] of [[320, 480], [960, 540], [1440, 900]]) {
    await cdp('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 1, mobile: false });
    await evaluate('SlideDeck.visibility.openSettings()');
    assert(await evaluate(`(() => { const r=document.querySelector('.visibility-dialog').getBoundingClientRect(); return r.left>=0 && r.top>=0 && r.right<=innerWidth && r.bottom<=innerHeight; })()`));
    const shot = await cdp('Page.captureScreenshot', { format: 'png' });
    await writeFile(path.join(browser.profile, `settings-${width}.png`), Buffer.from(shot.data, 'base64'));
    await evaluate('document.querySelector(".visibility-dialog").close()');
  }
  await evaluate('SlideDeck.visibility.openSettings(); document.querySelector(".visibility-download").click()');
  for (let i = 0; i < 50; i++) {
    try { settings = JSON.parse(await readFile(path.join(root, 'slide.visibility.json'), 'utf8')); break; }
    catch { await new Promise(resolve => setTimeout(resolve, 100)); }
  }
  assert.equal(settings.modes.length, 3, 'Settings download contains custom modes');
  settings.defaultMode = settings.modes[0].id;
  const lastId = await evaluate('SlideDeck.slides[2].dataset.slideId');
  settings.hidden[lastId] = [settings.modes[2].id];
  await writeFile(path.join(root, 'slide.visibility.json'), JSON.stringify(settings));
  const { root: document } = await cdp('DOM.getDocument');
  const { nodeId } = await cdp('DOM.querySelector', { nodeId: document.nodeId, selector: '.visibility-import input' });
  await cdp('DOM.setFileInputFiles', { nodeId, files: [path.join(root, 'slide.visibility.json')] });
  await settle();
  assert.equal(await evaluate('SlideDeck.visibility.mode'), settings.defaultMode, 'File import applies the default mode');
  await writeFile(path.join(root, 'invalid-import.json'), JSON.stringify({ ...settings, hidden: { otherDeck: [settings.modes[0].id] } }));
  await cdp('DOM.setFileInputFiles', { nodeId, files: [path.join(root, 'invalid-import.json')] });
  await settle();
  assert.deepEqual(await evaluate('SlideDeck.visibility.settings'), settings, 'Invalid imports leave the current settings intact');
  await evaluate('document.querySelector(".visibility-dialog").close()');
  await build(root);
  const selected = await exportSelection(target, { mode: '授業' });
  assert.equal(selected.visible.length, 2);
  const fixed = selectedHtml(selected, true);
  assert.equal(slideSections(fixed).length, 2);
  assert(!fixed.includes('<h1 class="slide__title">Model</h1>'));
  const single = path.join(root, 'lesson.html');
  const bundle = await run('scripts/bundle-single.mjs', [target, single, '--mode', '授業']);
  assert.equal(bundle.code, 0, bundle.output);
  await browser.load(single);
  assert.equal(await evaluate('SlideDeck.slides.length'), 2);
  assert.equal(await evaluate('SlideDeck.visibility.visibleSlides.length'), 2);
  assert.equal(await evaluate(`document.querySelectorAll('.visibility-edit').length`), 0, 'Fixed exports have no visibility editor');
  assert.deepEqual(browser.failed, []); assert.deepEqual(browser.external, []);
  const pdf = path.join(root, 'lesson.pdf');
  const exported = await run('scripts/export-pdf.mjs', [target, pdf, '--mode', '授業']);
  assert.equal(exported.code, 0, exported.output);
  const pdfData = (await readFile(pdf)).toString('latin1');
  assert.equal((pdfData.match(/\/Type\s*\/Page\b/g) || []).length, 2, 'PDF has exactly two pages and no blank final page');
  const repeated = await run('scripts/export-pdf.mjs', [target, pdf, '--mode', '授業']);
  assert.notEqual(repeated.code, 0); assert(repeated.output.includes('上書きしません'));
  const rebundledPdf = await run('scripts/export-pdf.mjs', [single, path.join(root, 'fixed.pdf')]);
  assert.equal(rebundledPdf.code, 0, rebundledPdf.output);
  await cp(path.join(repo, 'tools'), path.join(root, 'tools'), { recursive: true });
  await cp(path.join(repo, 'scripts'), path.join(root, 'scripts'), { recursive: true });
  const cli = path.join(root, 'tools/slide.mjs'), bulkOutput = path.join(root, 'bulk.pdf');
  const bulk = await run(cli, ['export', 'pdf', bulkOutput, '--all-modes', '--settings', path.join(root, 'slide.visibility.json')]);
  assert.equal(bulk.code, 0, bulk.output);
  const expected = { all: 3, 授業: 2, 配布: 3, 自習: 2 };
  for (const [suffix, pages] of Object.entries(expected)) {
    const data = (await readFile(path.join(root, `bulk-${suffix}.pdf`))).toString('latin1');
    assert.equal((data.match(/\/Type\s*\/Page\b/g) || []).length, pages, `Bulk ${suffix} PDF page count`);
  }
  const repeatedBulk = await run(cli, ['export', 'pdf', bulkOutput, '--all-modes']);
  assert.notEqual(repeatedBulk.code, 0); assert(repeatedBulk.output.includes('上書きしません'));
  const bulkSingle = await run(cli, ['export', 'single', path.join(root, 'bulk.html'), '--all-modes']);
  assert.equal(bulkSingle.code, 0, bulkSingle.output);
  for (const [suffix, pages] of Object.entries(expected)) assert.equal(slideSections(await readFile(path.join(root, `bulk-${suffix}.html`), 'utf8')).length, pages);
  await assert.rejects(exportSelection(target, { mode: '不明' }), /見つかりません/);
  const invalid = { ...settings, hidden: { nonexistent: [settings.modes[0].id] } };
  await writeFile(path.join(root, 'bad.json'), JSON.stringify(invalid));
  await assert.rejects(exportSelection(target, { settings: path.join(root, 'bad.json'), mode: 'all' }), /対象スライドが見つかりません/);
  await browser.load(target);
  await evaluate(`localStorage.setItem('html-slide-visibility-v1:' + location.pathname, '{broken')`);
  await browser.load(target);
  await evaluate('SlideDeck.visibility.setMode("all")');
  assert.equal(await evaluate(`localStorage.getItem('html-slide-visibility-v1:' + location.pathname)`), '{broken', 'Malformed settings are never overwritten');
  await evaluate(`localStorage.removeItem('html-slide-visibility-v1:' + location.pathname)`);
  await browser.load(target);
  await evaluate(`Storage.prototype.setItem = () => { throw new DOMException('quota', 'QuotaExceededError'); }; SlideDeck.visibility.setMode('all'); SlideDeck.visibility.openSettings()`);
  assert((await evaluate(`document.querySelector('.visibility-status').textContent`)).includes('保存できません'));
  assert.equal(await evaluate('SlideDeck.visibility.visibleSlides.length'), 3, 'Storage failure does not discard in-memory edits');
  assert.deepEqual(browser.errors, []);
  console.log(`PASS visibility UI, custom modes, navigation, numbering, timer, persistence, storage failures, fixed offline HTML and PDF page count\n${browser.profile}`);
} finally { browser.close(); await rm(root, { recursive: true, force: true }); }
